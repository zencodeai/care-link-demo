"""Typed named data-gateway boundary; core never receives business DB credentials."""

from typing import Protocol

from care_link_domain import Actor
from fastapi import Request


class BrowserSecurity(Protocol):
    def authenticate(self, request: Request) -> Actor: ...

    def csrf(self, request: Request, actor: Actor) -> None: ...


class ManualGateway(Protocol):
    def session_create(
        self, actor: Actor, key: str, data: dict[str, object]
    ) -> dict[str, object]: ...
    def session_read(self, actor: Actor, session_id: str) -> dict[str, object]: ...
    def messages_read(
        self, actor: Actor, session_id: str, *, limit: int = 50, cursor: str | None = None
    ) -> dict[str, object]: ...
    def queue_list(
        self, actor: Actor, *, limit: int = 50, cursor: str | None = None
    ) -> dict[str, object]: ...
    def operation_status(self, actor: Actor, operation_id: str) -> dict[str, object]: ...
    def channel_challenge_read(self, actor: Actor, session_id: str) -> dict[str, object]: ...
    def session_events(
        self, actor: Actor, session_id: str, last_event_id: int = 0
    ) -> list[dict[str, object]]: ...
    def session_disclosure(
        self, actor: Actor, key: str, data: dict[str, object], session_id: str
    ) -> dict[str, object]: ...
    def session_turns(
        self, actor: Actor, key: str, data: dict[str, object], session_id: str
    ) -> dict[str, object]: ...
    def session_assertions(
        self, actor: Actor, key: str, data: dict[str, object], session_id: str
    ) -> dict[str, object]: ...
    def session_choices(
        self, actor: Actor, key: str, data: dict[str, object], session_id: str
    ) -> dict[str, object]: ...
    def session_human_request(
        self, actor: Actor, key: str, data: dict[str, object], session_id: str
    ) -> dict[str, object]: ...
    def session_end(
        self, actor: Actor, key: str, data: dict[str, object], session_id: str
    ) -> dict[str, object]: ...
    def message_send(
        self, actor: Actor, key: str, data: dict[str, object], session_id: str
    ) -> dict[str, object]: ...
    def workforce_reserve(
        self, actor: Actor, key: str, data: dict[str, object], session_id: str
    ) -> dict[str, object]: ...
    def workforce_accept(
        self, actor: Actor, key: str, data: dict[str, object], session_id: str
    ) -> dict[str, object]: ...
    def workforce_prepare_transfer(
        self, actor: Actor, key: str, data: dict[str, object], session_id: str
    ) -> dict[str, object]: ...
    def workforce_confirm_transfer(
        self, actor: Actor, key: str, data: dict[str, object], session_id: str
    ) -> dict[str, object]: ...
    def workforce_transfer_failed(
        self, actor: Actor, key: str, data: dict[str, object], session_id: str
    ) -> dict[str, object]: ...
    def workforce_observe(
        self, actor: Actor, key: str, data: dict[str, object], session_id: str
    ) -> dict[str, object]: ...
    def workforce_takeover(
        self, actor: Actor, key: str, data: dict[str, object], session_id: str
    ) -> dict[str, object]: ...
    def channel_ack(
        self, actor: Actor, key: str, data: dict[str, object], session_id: str
    ) -> dict[str, object]: ...
    def continuation_rotate(
        self, actor: Actor, key: str, data: dict[str, object]
    ) -> dict[str, object]: ...
    def continuation_recover(
        self, actor: Actor, key: str, data: dict[str, object]
    ) -> dict[str, object]: ...
    def control_change(
        self, actor: Actor, key: str, data: dict[str, object]
    ) -> dict[str, object]: ...

    def continuation_issue(
        self, actor: Actor, key: str, data: dict[str, object], session_id: str
    ) -> dict[str, object]: ...
